export function BrandMark({
  id,
  size = 18,
  className,
}: {
  readonly id: BrandMarkId;
  readonly size?: number;
  readonly className?: string;
}): JSX.Element {
  const def = BRAND_MARKS[id] ?? BRAND_MARKS.generic;
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      role="presentation"
      aria-hidden="true"
      focusable="false"
      className={className}
      style={{ flexShrink: 0 }}
    >
      <path d={def.path} fill={def.tint} fillRule="evenodd" />
    </svg>
  );
}

export function BrandTile({
  id,
  size = 34,
  markSize,
}: {
  readonly id: BrandMarkId;
  readonly size?: number;
  readonly markSize?: number;
}): JSX.Element {
  const def = BRAND_MARKS[id] ?? BRAND_MARKS.generic;
  const style: CSSProperties = {
    display: "inline-flex",
    alignItems: "center",
    justifyContent: "center",
    width: size,
    height: size,
    borderRadius: 10,
    flexShrink: 0,
    background: `color-mix(in srgb, ${def.tint} 13%, transparent)`,
    border: `1px solid color-mix(in srgb, ${def.tint} 22%, transparent)`,
  };
  return (
    <span style={style} aria-hidden="true">
      <BrandMark id={id} size={markSize ?? Math.round(size * 0.55)} />
    </span>
  );
}
