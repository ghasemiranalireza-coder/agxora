/**
 * Business Catalog — recognition metadata for every supported business type.
 * Used by the Business Brain to reason differently per industry.
 */

import type { BusinessSize, BusinessType } from "./BusinessType";
import { BUSINESS_TYPE_META, getBusinessTypeMeta } from "./BusinessType";
import {
  getSpecializedMetrics,
  type MetricDefinition,
} from "./BusinessMetrics";

export interface BusinessCatalogEntry {
  readonly type: BusinessType;
  readonly label: string;
  readonly industry: string;
  readonly industryFamily: string;
  readonly description: string;
  readonly defaultSize: BusinessSize;
  readonly defaultCurrency: string;
  readonly defaultDepartments: readonly string[];
  readonly typicalServices: readonly string[];
  readonly typicalProducts: readonly string[];
  readonly typicalCustomers: readonly string[];
  readonly typicalSuppliers: readonly string[];
  readonly typicalLocations: readonly string[];
  readonly defaultGoals: readonly string[];
  readonly defaultKpis: readonly string[];
  readonly painPoints: readonly string[];
  /** Domains the AI should reason about for this business. */
  readonly reasoningDomains: readonly string[];
  readonly specializedMetrics: readonly MetricDefinition[];
}

function entry(
  type: BusinessType,
  partial: Omit<
    BusinessCatalogEntry,
    "type" | "label" | "industryFamily" | "description" | "specializedMetrics" | "industry"
  > & { industry?: string },
): BusinessCatalogEntry {
  const meta = getBusinessTypeMeta(type);
  return {
    type,
    label: meta.label,
    industry: partial.industry ?? meta.label,
    industryFamily: meta.industryFamily,
    description: meta.description,
    specializedMetrics: getSpecializedMetrics(type),
    ...partial,
  };
}

