export function getCatalogEntry(type: BusinessType): BusinessCatalogEntry {
  const found = BUSINESS_CATALOG.find((item) => item.type === type);
  if (!found) {
    throw new Error(`No catalog entry for business type: ${type}`);
  }
  return found;
}

export function listCatalog(): readonly BusinessCatalogEntry[] {
  return BUSINESS_CATALOG;
}

/** Ensure every BusinessType has catalog coverage (dev-time guard). */
export function assertCatalogComplete(): void {
  for (const meta of BUSINESS_TYPE_META) {
    getCatalogEntry(meta.type);
  }
}
