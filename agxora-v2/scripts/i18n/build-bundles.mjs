#!/usr/bin/env node
/**
 * Merge per-namespace JSON files into locale bundles and generate catalog.ts.
 * Run: node scripts/i18n/build-bundles.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "../..");
const MESSAGES = path.join(ROOT, "app/lib/i18n/messages");
const BUNDLES = path.join(ROOT, "app/lib/i18n/bundles");
const CATALOG = path.join(ROOT, "app/lib/i18n/catalog.ts");

const LOCALES = [
  "en", "de", "fa", "zh-CN", "zh-TW", "ja", "nl", "nl-BE", "fr", "fr-BE",
  "de-BE", "es", "it", "pt", "pt-BR", "ru", "tr", "ar", "ko", "pl", "uk",
  "hi", "id", "vi",
];

const NAMESPACES = [
  "common", "navigation", "pricing", "billing", "settings", "errors",
  "dashboard", "auth", "crm", "finance", "documents", "landing",
  "ui", "projects", "automation", "team", "customers", "ai", "agents",
  "integrations", "intelligence", "legal", "onboarding", "creator",
  "backend", "workspace", "iam", "businessAgent",
];

function readJson(filePath) {
  if (!fs.existsSync(filePath)) return {};
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function deepMerge(target, source) {
  for (const [key, value] of Object.entries(source)) {
    if (
      value &&
      typeof value === "object" &&
      !Array.isArray(value) &&
      target[key] &&
      typeof target[key] === "object" &&
      !Array.isArray(target[key])
    ) {
      deepMerge(target[key], value);
    } else {
      target[key] = value;
    }
  }
  return target;
}

/** Deep-merge locale onto English fallback for missing keys. */
function mergeWithFallback(localeTree, enTree) {
  const out = structuredClone(enTree);
  deepMerge(out, localeTree);
  return out;
}

fs.mkdirSync(BUNDLES, { recursive: true });

const validated = spawnSync(
  process.execPath,
  [path.join(__dirname, "validate-i18n.mjs")],
  { stdio: "inherit" },
);
if (validated.status) process.exit(validated.status);

const enBundle = {};
for (const ns of NAMESPACES) {
  enBundle[ns] = readJson(path.join(MESSAGES, "en", `${ns}.json`));
}
fs.writeFileSync(
  path.join(BUNDLES, "en.json"),
  JSON.stringify(enBundle, null, 2) + "\n",
);

for (const locale of LOCALES) {
  if (locale === "en") continue;
  const localeTree = {};
  for (const ns of NAMESPACES) {
    localeTree[ns] = readJson(path.join(MESSAGES, locale, `${ns}.json`));
  }
  const merged = mergeWithFallback(localeTree, enBundle);
  fs.writeFileSync(
    path.join(BUNDLES, `${locale}.json`),
    JSON.stringify(merged, null, 2) + "\n",
  );
}

const importLines = LOCALES.map(
  (loc) => `import bundle_${loc.replace(/-/g, "_")} from "./bundles/${loc}.json";`,
);
const catalogEntries = LOCALES.map(
  (loc) => `  "${loc}": bundle_${loc.replace(/-/g, "_")} as MessageTree,`,
);

const catalogSource = `/**
 * Message catalog loader — AUTO-GENERATED by scripts/i18n/build-bundles.mjs
 * Do not edit manually. Run: node scripts/i18n/build-bundles.mjs
 */

import type { AppLocale } from "./locale";
import { DEFAULT_LOCALE } from "./locale";

${importLines.join("\n")}

export type MessageTree = {
${NAMESPACES.map((ns) => `  readonly ${ns}: Record<string, unknown>;`).join("\n")}
};

const CATALOGS: Readonly<Record<AppLocale, MessageTree>> = {
${catalogEntries.join("\n")}
};

export function getCatalog(locale: AppLocale): MessageTree {
  return CATALOGS[locale] ?? CATALOGS[DEFAULT_LOCALE];
}

export function getFallbackCatalog(): MessageTree {
  return CATALOGS[DEFAULT_LOCALE];
}
`;

fs.writeFileSync(CATALOG, catalogSource);
console.log(`Built ${LOCALES.length} locale bundles → app/lib/i18n/bundles/`);
